CREATE TABLE tenants (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT UNIQUE, webhook_url TEXT);
CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, tenant_id INTEGER, username TEXT, password TEXT, role TEXT);
CREATE TABLE documents (id INTEGER PRIMARY KEY AUTOINCREMENT, tenant_id INTEGER, filename TEXT, size INTEGER, uploaded_by TEXT, uploaded_at TEXT);
CREATE TABLE shares (id INTEGER PRIMARY KEY AUTOINCREMENT, document_id INTEGER);
CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT);
